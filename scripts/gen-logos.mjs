// Names whose obvious slug belongs to an unrelated brand.
const SKIP = new Set(['mint', 'aha', 'zepto-pass', 'dish-tv', 'sun-nxt', 'sun-direct', 'times-of-india-plus', 'times-prime', 'the-ken', 'flo', 'cox', 'optimum', 'you-broadband', 'grok', 'box', 'max', 'viki', 'd2h', 'altt', 'excitel', 'lovable', 'brilliant', 'hinge', 'oura', 'everand', 'peacock']);

const GENERIC = new Set(['plus', 'pro', 'premium', 'advanced', 'unlimited', 'go', 'pass', 'one', 'nitro', 'turbo', 'prepaid', 'postpaid', 'mobile', 'fiber', 'wireless', 'gold', 'pink', 'tv', 'music', 'ai', 'media', 'online', 'choice']);

function find(app) {
  for (const slug of ALIAS[app.id] ?? []) if (bySlug.has(slug)) return bySlug.get(slug);
  if (SKIP.has(app.id)) return null;
  const words = app.id.split('-');
  const full = words.join('');
  if (bySlug.has(full)) return bySlug.get(full);
  // Drop trailing plan words only: "discord-nitro" -> "discord", never "sun-nxt" -> "sun".
  for (let end = words.length - 1; end >= 1; end--) {
    if (!GENERIC.has(words[end])) break;
    const slug = words.slice(0, end).join('');
    if (bySlug.has(slug)) return bySlug.get(slug);
  }
  return null;
}

const matched = {};
const unmatched = [];
for (const app of CATALOG) {
  const icon = find(app);
  if (icon) matched[app.id] = { title: icon.title, hex: `#${icon.hex}`, path: icon.path };
  else unmatched.push(app.name);
}

const out = `// GENERATED by scripts/gen-logos.mjs from Simple Icons (CC0). Do not edit by hand.
// Brand marks are trademarks of their owners, used here only to identify each service.

export interface BrandLogo {
  title: string;
  hex: string;
  path: string;
}

export const LOGOS: Record<string, BrandLogo> = ${JSON.stringify(matched, null, 2)};
`;
const target = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../src/domain/logos.gen.ts');
writeFileSync(target, out);
